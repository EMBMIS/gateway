#!/usr/bin/env node
/**
 * Writes src/styles/tokens.generated.css from scripts/design/palette.mjs and
 * checks every pair in CONTRAST_PAIRS against WCAG 2.2 AA, in both themes.
 * Exits non-zero on any failure, so it can gate CI.
 *
 *   node scripts/design/build-tokens.mjs           write + check
 *   node scripts/design/build-tokens.mjs --check   check only
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { STEPS, SURFACE, RAMPS, CONTRAST_PAIRS } from './palette.mjs'

const here = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.join(here, '../../src/styles/tokens.generated.css')

const hexToRgb = (hex) => {
  const h = hex.replace('#', '')
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16))
}
const channel = (c) => {
  const s = c / 255
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4
}
const luminance = (hex) => {
  const [r, g, b] = hexToRgb(hex).map(channel)
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}
export const contrast = (a, b) => {
  const [x, y] = [luminance(a), luminance(b)].sort((m, n) => n - m)
  return (x + 0.05) / (y + 0.05)
}

function resolve(ref, theme) {
  if (ref.startsWith('#')) return ref
  if (SURFACE[theme][ref]) return SURFACE[theme][ref]
  const [kind, ramp, step] = ref.split('.')
  return RAMPS[ramp][theme][kind][STEPS.indexOf(step)]
}

let failures = 0
for (const theme of ['light', 'dark']) {
  for (const [fg, bg, min, label] of CONTRAST_PAIRS) {
    const ratio = contrast(resolve(fg, theme), resolve(bg, theme))
    if (ratio < min) {
      failures += 1
      console.error(`✗ ${theme.padEnd(5)} ${label}: ${fg} on ${bg} = ${ratio.toFixed(2)} (needs ${min})`)
    }
  }
}

const rgb = (hex) => hexToRgb(hex).join(' ')
function block(theme) {
  const lines = []
  for (const [name, hex] of Object.entries(SURFACE[theme])) lines.push(`  --${name}: ${rgb(hex)};`)
  for (const [ramp, themes] of Object.entries(RAMPS)) {
    themes[theme].bg.forEach((hex, i) => lines.push(`  --c-${ramp}-${STEPS[i]}: ${rgb(hex)};`))
    themes[theme].text.forEach((hex, i) => lines.push(`  --t-${ramp}-${STEPS[i]}: ${rgb(hex)};`))
  }
  return lines.join('\n')
}

const css = `/* GENERATED by scripts/design/build-tokens.mjs from palette.mjs. Do not edit.
 * Channels are space-separated RGB so Tailwind's opacity modifiers work:
 * rgb(var(--c-brand-600) / 0.1). Semantic tokens live in tokens.css. */
:root,
.light {
${block('light')}
}
.dark {
${block('dark')}
}
`

if (!process.argv.includes('--check')) fs.writeFileSync(OUT, css)
if (failures) {
  console.error(`\n${failures} contrast pair(s) below AA.`)
  process.exit(1)
}
console.log(`✓ ${CONTRAST_PAIRS.length * 2} contrast pairs pass AA in light and dark.`)
